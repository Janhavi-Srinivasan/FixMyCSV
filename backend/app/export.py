def _literal(v):
    return repr(v) if not isinstance(v, (dict, list)) else (
        "{" + ", ".join(f"{_literal(k)}: {_literal(x)}" for k, x in v.items()) + "}" if isinstance(v, dict)
        else "[" + ", ".join(_literal(x) for x in v) + "]")


def build_script(ds: dict, steps: list[dict]) -> str:
    """`steps` = enabled, successfully-applied steps in order."""
    used = []
    for st in steps:
        if st["op"] not in used:
            used.append(st["op"])
    helpers, imports = [], set()
    for op in used:
        for h in OPERATIONS[op]["helpers"]:
            if h not in helpers:
                helpers.append(h)
        imports.update(OPERATIONS[op]["imports"])
    needs = ["pandas", "numpy"]
    if any(o in ("drop_anomalous_rows",) for o in used):
        needs.append("scikit-learn")
    if ds["kind"] == "excel":
        needs.append("openpyxl")
    script_name = "clean_data.py"

    lines = [HEADER.format(filename=ds["filename"], count=len(steps), script_name=script_name, needs=", ".join(needs))]
    lines.append("import sys\n")
    lines.append("import numpy as np")
    lines.append("import pandas as pd")
    for imp in sorted(imports):
        lines.append(f"import {imp}")
    lines.append("")
    lines.append("")

    if helpers or used:
        lines.append("# --- helper functions " + "-" * 50)
    for h in helpers:
        lines.append(inspect.getsource(getattr(transforms, h)).rstrip())
        lines.append("")
        lines.append("")
    lines.append("# --- cleaning steps " + "-" * 52)
    for op in used:
        lines.append(inspect.getsource(OPERATIONS[op]["fn"]).rstrip())
        lines.append("")
        lines.append("")

    read = "pd.read_excel(path" + (f", sheet_name={ds['sheet']!r}" if ds["sheet"] else "") + ")" if ds["kind"] == "excel" else "pd.read_csv(path)"
    lines.append("# --- pipeline " + "-" * 58)
    lines.append("def clean(df):")
    if not steps:
        lines.append("    # No cleaning steps were applied.")
    for i, st in enumerate(steps, 1):
        label = OPERATIONS[st["op"]]["label"]
        lines.append(f"    # Step {i}: {label}")
        for chunk in textwrap.wrap(st.get("reason") or "", 92):
            lines.append(f"    #   {chunk}")
        params = {k: v for k, v in st["params"].items() if v is not None and v != "" and v != []}
        args = "".join(f",\n        {k}={_literal(v)}" for k, v in params.items())
        lines.append(f"    df = {st['op']}(df{args})" if not args else f"    df = {st['op']}(\n        df{args},\n    )")
        lines.append("")
    lines.append("    return df")
    lines.append("")
    lines.append("")
    lines.append(f"DEFAULT_INPUT = {ds['filename']!r}")
    lines.append(f"DEFAULT_OUTPUT = {('cleaned_' + ds['name'] + '.csv')!r}")
    lines.append("")
    lines.append("")
    lines.append("def main():")
    lines.append("    path = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_INPUT")
    lines.append("    out_path = sys.argv[2] if len(sys.argv) > 2 else DEFAULT_OUTPUT")
    lines.append(f"    df = {read}")
    lines.append("    before = df.shape")
    lines.append("    df = clean(df)")
    lines.append("    df.to_csv(out_path, index=False)")
    lines.append('    print(f"{path}: {before[0]} rows x {before[1]} cols  ->  {out_path}: {df.shape[0]} rows x {df.shape[1]} cols")')
    lines.append("")
    lines.append("")
    lines.append('if __name__ == "__main__":')
    lines.append("    main()")
    return "\n".join(lines) + "\n"


def build_changelog(ds: dict, results, before_q: dict, after_q: dict) -> str:
    out = [f"# Cleaning report: {ds['filename']}", "",
           f"Quality score: **{before_q['overall']} → {after_q['overall']}**  "
           f"(rows {before_q['rows']} → {after_q['rows']}, issues {before_q['issue_count']} → {after_q['issue_count']})", ""]
    n = 0
    for r in results:
        label = OPERATIONS[r.step["op"]]["label"]
        if r.status == "disabled":
            out += [f"- ~~{label}~~ (undone)"]
            continue
        n += 1
        if r.status == "error":
            out += [f"{n}. **{label}** — skipped: {r.error}"]
            continue
        d = r.diff
        bits = []
        if d["rows_removed"]:
            bits.append(f"{d['rows_removed']} rows removed")
        if d["cells_changed"]:
            bits.append(f"{d['cells_changed']} cells changed")
        if d["columns_dropped"]:
            bits.append("dropped " + ", ".join(d["columns_dropped"]))
        out += [f"{n}. **{label}** — {', '.join(bits) or 'no effect'}"]
        if r.step.get("reason"):
            out += [f"   - Why: {r.step['reason']}"]
        for s in d["samples"][:3]:
            out += [f"   - row {s['row']}, {s['column']}: `{s['before']}` → `{s['after']}`"]
    return "\n".join(out) + "\n"
